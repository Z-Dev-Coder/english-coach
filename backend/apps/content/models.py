from django.conf import settings
from django.db import models
from django.utils import timezone

from apps.profiles.constants import CEFR


class ContentSource(models.Model):
    """A feed to pull real-world English from."""

    name = models.CharField(max_length=120)
    feed_url = models.URLField(unique=True)
    homepage = models.URLField(blank=True)
    topic = models.CharField(
        max_length=40, help_text="technology, science, world, business, entertainment…"
    )
    is_active = models.BooleanField(default=True)
    last_fetched_at = models.DateTimeField(null=True, blank=True)
    last_error = models.TextField(blank=True)
    article_count = models.PositiveIntegerField(default=0)

    class Meta:
        ordering = ["topic", "name"]

    def __str__(self) -> str:
        return f"{self.name} ({self.topic})"

    def record_success(self, added: int) -> None:
        self.last_fetched_at = timezone.now()
        self.last_error = ""
        self.article_count += added
        self.save(update_fields=["last_fetched_at", "last_error", "article_count"])

    def record_failure(self, message: str) -> None:
        self.last_fetched_at = timezone.now()
        self.last_error = message[:500]
        self.save(update_fields=["last_fetched_at", "last_error"])


class Article(models.Model):
    """A real-world item, stored as metadata plus *our own* learning material.

    **Copyright is the design constraint here.** We never fetch or store the
    full body of a copyrighted article. What is stored is:

    - metadata (title, link, date, source) — facts, and the link is the point;
    - `summary`, the publisher's own syndication summary, which is what an RSS
      feed exists to distribute, capped in length;
    - `adapted_text` and the exercises, which are written by our own model
      *about* the story rather than copied from it.

    The learner is always sent to the original to read it in full. That is the
    difference between a study aid and a scraper.
    """

    class Status(models.TextChoices):
        FETCHED = "fetched", "Fetched"
        PREPARED = "prepared", "Learning material ready"
        FAILED = "failed", "Preparation failed"

    source = models.ForeignKey(
        ContentSource, on_delete=models.CASCADE, related_name="articles"
    )
    guid = models.CharField(max_length=500, help_text="The feed's own identifier for this entry.")
    url = models.URLField(max_length=800)
    title = models.CharField(max_length=400)
    summary = models.TextField(
        blank=True, help_text="The publisher's syndication summary. Never the full article."
    )
    author = models.CharField(max_length=200, blank=True)
    topic = models.CharField(max_length=40, blank=True)
    published_at = models.DateTimeField(null=True, blank=True)
    fetched_at = models.DateTimeField(auto_now_add=True)

    # --- Learning material, generated by us ---
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.FETCHED)
    level = models.CharField(max_length=2, choices=CEFR.choices, blank=True)
    adapted_text = models.TextField(
        blank=True, help_text="Our own short retelling, written at the learner's level."
    )
    vocabulary = models.JSONField(default=list, blank=True)
    phrases = models.JSONField(default=list, blank=True)
    questions = models.JSONField(default=list, blank=True)
    speaking_prompt = models.TextField(blank=True)
    writing_prompt = models.TextField(blank=True)
    prepared_at = models.DateTimeField(null=True, blank=True)
    preparation_error = models.TextField(blank=True)

    class Meta:
        ordering = ["-published_at", "-fetched_at"]
        constraints = [
            # Idempotent ingestion: re-reading a feed can never duplicate an
            # entry, whether the publisher identifies it by guid or by URL.
            models.UniqueConstraint(fields=["source", "guid"], name="uniq_article_guid"),
            models.UniqueConstraint(fields=["url"], name="uniq_article_url"),
        ]
        indexes = [
            models.Index(fields=["topic", "-published_at"]),
            models.Index(fields=["status", "-published_at"]),
        ]

    def __str__(self) -> str:
        return self.title

    @property
    def is_prepared(self) -> bool:
        return self.status == self.Status.PREPARED

    @property
    def has_material(self) -> bool:
        """Enough to study, even if preparation only partly succeeded."""
        return bool(self.adapted_text or self.vocabulary or self.questions)


class Scene(models.Model):
    """A screen-style dialogue lesson: original writing, not a transcript.

    Real film and TV dialogue is copyrighted, so scenes are written the way
    people talk on screen -- interruptions, idioms, phrasal verbs, reductions --
    in the genres learners watch. Shared across learners: a scene is content,
    and who has finished it lives in SceneProgress.
    """

    class Source(models.TextChoices):
        SEED = "seed", "Hand-written"
        AI = "ai", "Generated"
        VOA = "voa", "Real recording (VOA)"

    slug = models.SlugField(max_length=80, unique=True)
    title = models.CharField(max_length=200)
    genre = models.CharField(max_length=40, blank=True)
    level = models.CharField(max_length=2, choices=CEFR.choices, default=CEFR.B1)
    setting = models.TextField(blank=True)
    lines = models.JSONField(default=list, help_text="[{speaker, text}] in order.")
    expressions = models.JSONField(
        default=list, help_text="[{expression, meaning, literal_trap, example}]"
    )
    questions = models.JSONField(default=list, blank=True)
    source = models.CharField(max_length=8, choices=Source.choices, default=Source.SEED)
    audio_url = models.URLField(blank=True, max_length=500, help_text="Real human recording of the scene.")
    audio_credit = models.CharField(blank=True, max_length=120)
    source_url = models.URLField(blank=True, max_length=500, help_text="Page the scene came from.")
    word_timings = models.JSONField(
        default=list, blank=True, help_text="[[word_index, seconds]] over the lines joined by spaces."
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["level", "id"]

    def __str__(self) -> str:
        return f"{self.title} ({self.level})"


class VideoLesson(models.Model):
    """A real YouTube video, watched on YouTube, with our lesson around it.

    Found from a channel feed when a learner needs a new video, and prepared
    then. The app never plays or copies the video; everything stored besides
    the title and the channel's own description is our writing.
    """

    video_id = models.CharField(max_length=20, unique=True)
    title = models.CharField(max_length=300)
    channel = models.CharField(max_length=120)
    level = models.CharField(max_length=2, choices=CEFR.choices, default=CEFR.B1)
    kind = models.CharField(max_length=40, blank=True, help_text="Conversation, street interviews, talk…")
    duration_seconds = models.PositiveIntegerField(default=0)
    description = models.TextField(blank=True, help_text="The channel's own description, from its feed.")
    summary = models.TextField(blank=True)
    expressions = models.JSONField(default=list, blank=True, help_text="[{expression, meaning, example}]")
    listen_for = models.JSONField(default=list, blank=True, help_text="Short tasks to do while watching.")
    questions = models.JSONField(default=list, blank=True)
    speaking_prompt = models.TextField(blank=True)
    prepared_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["level", "id"]

    def __str__(self) -> str:
        return f"{self.title} ({self.level})"

    @property
    def url(self) -> str:
        return f"https://www.youtube.com/watch?v={self.video_id}"

    @property
    def thumbnail(self) -> str:
        return f"https://i.ytimg.com/vi/{self.video_id}/hqdefault.jpg"


class VideoProgress(models.Model):
    """A video given to a learner; finished once completed_at is set.

    At most one unfinished row per learner is their current video.
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="video_progress"
    )
    video = models.ForeignKey(VideoLesson, on_delete=models.CASCADE, related_name="progress")
    assigned_at = models.DateTimeField(default=timezone.now)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["user", "video"], name="uniq_video_progress")
        ]


class SceneProgress(models.Model):
    """That a learner finished a scene. One row per learner per scene."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="scene_progress"
    )
    scene = models.ForeignKey(Scene, on_delete=models.CASCADE, related_name="progress")
    completed_at = models.DateTimeField(default=timezone.now)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["user", "scene"], name="uniq_scene_progress")
        ]
