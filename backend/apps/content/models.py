from django.db import models
from django.utils import timezone

from apps.profiles.constants import CEFR


class ContentSource(models.Model):
    """A feed to pull real-world English from."""

    name = models.CharField(max_length=120)
    feed_url = models.URLField(unique=True)
    homepage = models.URLField(blank=True)
    topic = models.CharField(
        max_length=40, help_text="technology, science, world, business, entertainment…"
    )
    is_active = models.BooleanField(default=True)
    last_fetched_at = models.DateTimeField(null=True, blank=True)
    last_error = models.TextField(blank=True)
    article_count = models.PositiveIntegerField(default=0)

    class Meta:
        ordering = ["topic", "name"]

    def __str__(self) -> str:
        return f"{self.name} ({self.topic})"

    def record_success(self, added: int) -> None:
        self.last_fetched_at = timezone.now()
        self.last_error = ""
        self.article_count += added
        self.save(update_fields=["last_fetched_at", "last_error", "article_count"])

    def record_failure(self, message: str) -> None:
        self.last_fetched_at = timezone.now()
        self.last_error = message[:500]
        self.save(update_fields=["last_fetched_at", "last_error"])


class Article(models.Model):
    """A real-world item, stored as metadata plus *our own* learning material.

    **Copyright is the design constraint here.** We never fetch or store the
    full body of a copyrighted article. What is stored is:

    - metadata (title, link, date, source) — facts, and the link is the point;
    - `summary`, the publisher's own syndication summary, which is what an RSS
      feed exists to distribute, capped in length;
    - `adapted_text` and the exercises, which are written by our own model
      *about* the story rather than copied from it.

    The learner is always sent to the original to read it in full. That is the
    difference between a study aid and a scraper.
    """

    class Status(models.TextChoices):
        FETCHED = "fetched", "Fetched"
        PREPARED = "prepared", "Learning material ready"
        FAILED = "failed", "Preparation failed"

    source = models.ForeignKey(
        ContentSource, on_delete=models.CASCADE, related_name="articles"
    )
    guid = models.CharField(max_length=500, help_text="The feed's own identifier for this entry.")
    url = models.URLField(max_length=800)
    title = models.CharField(max_length=400)
    summary = models.TextField(
        blank=True, help_text="The publisher's syndication summary. Never the full article."
    )
    author = models.CharField(max_length=200, blank=True)
    topic = models.CharField(max_length=40, blank=True)
    published_at = models.DateTimeField(null=True, blank=True)
    fetched_at = models.DateTimeField(auto_now_add=True)

    # --- Learning material, generated by us ---
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.FETCHED)
    level = models.CharField(max_length=2, choices=CEFR.choices, blank=True)
    adapted_text = models.TextField(
        blank=True, help_text="Our own short retelling, written at the learner's level."
    )
    vocabulary = models.JSONField(default=list, blank=True)
    phrases = models.JSONField(default=list, blank=True)
    questions = models.JSONField(default=list, blank=True)
    speaking_prompt = models.TextField(blank=True)
    writing_prompt = models.TextField(blank=True)
    prepared_at = models.DateTimeField(null=True, blank=True)
    preparation_error = models.TextField(blank=True)

    class Meta:
        ordering = ["-published_at", "-fetched_at"]
        constraints = [
            # Idempotent ingestion: re-reading a feed can never duplicate an
            # entry, whether the publisher identifies it by guid or by URL.
            models.UniqueConstraint(fields=["source", "guid"], name="uniq_article_guid"),
            models.UniqueConstraint(fields=["url"], name="uniq_article_url"),
        ]
        indexes = [
            models.Index(fields=["topic", "-published_at"]),
            models.Index(fields=["status", "-published_at"]),
        ]

    def __str__(self) -> str:
        return self.title

    @property
    def is_prepared(self) -> bool:
        return self.status == self.Status.PREPARED

    @property
    def has_material(self) -> bool:
        """Enough to study, even if preparation only partly succeeded."""
        return bool(self.adapted_text or self.vocabulary or self.questions)
